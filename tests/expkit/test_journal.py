def test_write_entry_creates_the_expected_files(tmp_path):
    out = tmp_path / "out"
    out.mkdir()
    journal.write_entry(make_run(tmp_path), out)
    files = sorted(str(p.relative_to(out)) for p in out.rglob("*") if p.is_file())
    assert [name for name in files if "/styles/" not in name] == [
        "generated/001-toy/20260101-120000-abcd/entry.tex",
        "generated/001-toy/20260101-120000-abcd/loss.pdf",
        "generated/macros.sty",
        "journal.tex",
    ]
    assert [name for name in files if "/styles/" in name] == [
        f"generated/styles/{style}.sty" for style in STYLES
    ]


def test_entry_contains_the_facts(tmp_path):
    out = tmp_path / "out"
    out.mkdir()
    run_dir = make_run(tmp_path)
    journal.write_entry(run_dir, out)
    entry = (out / "generated/001-toy/20260101-120000-abcd/entry.tex").read_text()
    first_line = entry.splitlines()[0]
    assert first_line == f"% Generated by expkit {expkit.__version__} from run 20260101-120000-abcd."
    assert "train.lr" not in entry  # the config is not part of an entry
    assert r"\expcode{Run}{20260101-120000-abcd}" in entry
    assert r"\expfact{Duration}{" in entry
    # Order: the facts that identify the run, then the results.
    assert entry.index(r"\end{expinfo}") < entry.index(r"\begin{expmetrics}") < entry.index(r"\expfigure")
    assert r"\expmetric{loss}{0.01235}" in entry
    assert r"\expmetric{val\_acc}{0.9}" in entry
    assert r"\expfigure{generated/001-toy/20260101-120000-abcd/loss.pdf}" in entry
    assert "expwandb" not in entry  # no URL recorded


