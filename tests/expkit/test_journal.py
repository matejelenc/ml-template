def _latex_compiler():
    for name in ("tectonic", "latexmk", "pdflatex"):
        if shutil.which(name):
            return name
    return None


@pytest.mark.skipif(_latex_compiler() is None, reason="no LaTeX compiler installed")
@pytest.mark.parametrize("style", STYLES)
def test_every_style_compiles(tmp_path, style):
    """Each style must define everything the macros need, for the journal and for reports."""
    project = tmp_path / "project"
    project.mkdir()
    journal.write_macros(project)
    (project / "all.tex").write_text(
        "\\documentclass{article}\n\\usepackage[%s]{generated/macros}\n"
        % style
        + "\\title{T}\\project{P}\\author{A}\\supervisors{S}\n\\begin{document}\n\\titleblock\n"
        "\\entry{2026-01-01}\n\\experiment{001-toy}\n"
        "\\begin{expinfo}\\expcode{Run}{r}\\expfact{Duration}{1 s}\\expwandb{https://x.y}\\expdirty\\end{expinfo}\n"
        "\\about{A.}\\hypothesis{}\n\\meeting{Ana}{Topics.}{Steps.}\n\\other\nText.\n\\other[Title]\nText.\n"
        "\\remark{R.}\\question{Q?}\\question[Ana]{Q?}\\issue{I.}\n\\end{document}\n"
    )
    command = {
        "tectonic": ["tectonic", "all.tex"],
        "latexmk": ["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", "all.tex"],
        "pdflatex": ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "all.tex"],
    }[_latex_compiler()]
    result = subprocess.run(command, cwd=project, capture_output=True, text=True)
    assert result.returncode == 0, result.stdout[-3000:] + result.stderr[-3000:]


