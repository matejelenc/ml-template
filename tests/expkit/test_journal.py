def test_tex_escape():
    assert journal.tex_escape("train_loss 50% {a} #1 $x$ a&b") == (
        r"train\_loss 50\% \{a\} \#1 \$x\$ a\&b"
    )
    assert journal.tex_escape("a\\b~c^d") == r"a\textbackslash{}b\textasciitilde{}c\textasciicircum{}d"


